@Injectable({ providedIn: 'root' })
export class I18nService {
  readonly languages: Array<{ code: AppLanguage; label: string }> = [
    { code: 'es', label: translations.es['common.spanish'] },
    { code: 'en', label: translations.en['common.english'] },
  ];

  private readonly currentLanguage = signal<AppLanguage>(this.initialLanguage());
  readonly language = this.currentLanguage.asReadonly();
  readonly dictionary = computed(() => translations[this.currentLanguage()]);

  setLanguage(language: AppLanguage): void {
    this.currentLanguage.set(language);
    localStorage.setItem(storageKey, language);
    document.documentElement.lang = language;
  }

  t(key: string): string {
    const current = this.dictionary() as Record<string, string>;
    const fallback = translations.es as Record<string, string>;
    return current[key] ?? fallback[key] ?? key;
  }

  private initialLanguage(): AppLanguage {
    const stored = localStorage.getItem(storageKey);
    if (stored === 'es' || stored === 'en') {
      document.documentElement.lang = stored;
      return stored;
    }

    document.documentElement.lang = 'es';
    return 'es';
  }
}
